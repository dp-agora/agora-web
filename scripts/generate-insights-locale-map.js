/**
 * Generates src/lib/insights-locale-map.ts from content/insights/*.md frontmatter.
 * Run before build when adding or changing insights: node scripts/generate-insights-locale-map.js
 */
const fs = require('fs');
const path = require('path');
const matter = require('gray-matter');

const contentDir = path.join(process.cwd(), 'content/insights');
const outPath = path.join(process.cwd(), 'src/lib/insights-locale-map.ts');

if (!fs.existsSync(contentDir)) {
  fs.writeFileSync(outPath, `// No content/insights directory - run script when insights exist\nexport const insightsLocaleMap: Record<string, { en: string; es: string }> = {};\n`);
  process.exit(0);
}

const files = fs.readdirSync(contentDir).filter((f) => f.endsWith('.md'));
const bySlug = {};

for (const file of files) {
  const fullPath = path.join(contentDir, file);
  const content = fs.readFileSync(fullPath, 'utf8');
  const { data } = matter(content);
  const slug = data.slug;
  const translationSlug = data.translationSlug;
  const lang = data.lang;
  if (!slug || !translationSlug || !lang) continue;
  const enSlug = lang === 'en' ? slug : translationSlug;
  const esSlug = lang === 'es' ? slug : translationSlug;
  const entry = { en: enSlug, es: esSlug };
  bySlug[slug] = entry;
  bySlug[translationSlug] = entry;
}

const ts = `/**
 * Map of insight slug -> { en, es } slugs for locale switching.
 * Generated by scripts/generate-insights-locale-map.js - do not edit by hand.
 */
export const insightsLocaleMap: Record<string, { en: string; es: string }> = ${JSON.stringify(bySlug, null, 2)};
`;

fs.writeFileSync(outPath, ts);
console.log('Wrote', outPath, 'with', Object.keys(bySlug).length, 'slug entries');